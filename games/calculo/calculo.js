function renderReview() {
  if (!state.learned.length) {
    show(el("p", { class: "placeholder" }, t("nothing-learned")), button(t("home"), () => { view = { phase: "hub" }; render(); }, "btn big ghost"));
    return;
  }
  const selected = new Set(view.selected);
  const back = { phase: "review", mode: "review", selected: view.selected };
  const message = el("p", { class: "hint" });

  const list = el("ul", { class: "review-list" }, STRATEGIES.filter((s) => state.learned.includes(s.id)).map((s) => {
    const box = el("input", {
      type: "checkbox",
      checked: selected.has(s.id),
      onchange: (e) => {
        if (e.target.checked) selected.add(s.id); else selected.delete(s.id);
        view.selected = [...selected];
        back.selected = view.selected;
      },
    });
    return el("li", {},
      el("label", {}, box, `${s.icon} ${tr(s.name)}`),
      button(t("view"), () => go({ phase: "learn", mode: "review", stratId: s.id, back }), "btn ghost"));
  }));

  const needOne = (fn) => () => {
    if (!selected.size) { message.textContent = t("select-one"); return; }
    fn([...selected]);
  };

  show(
    el("div", { class: "card" }, el("h2", {}, t("review-title")), el("p", { class: "hint" }, t("review-help")), list, message),
    el("div", { class: "stack" },
      button(t("review-practice"), needOne((ids) => go({ phase: "practice", mode: "review", ids, i: 0, problem: newPractice(pick(ids)), shown: 0, back })), "btn big"),
      button(t("review-round"), needOne((ids) => go({ phase: "round-intro", mode: "review", ids, back })), "btn big"),
      button(t("home"), () => { view = { phase: "hub" }; render(); }, "btn big ghost")),
  );
}

