const { t } = I18N;
document.title = t("title.page");

const STORAGE_KEY = "family-games:calculo";
const EXERCISES = 5;     // ejercicios guiados por estrategia
const ROUND_LENGTH = 10; // operaciones por ronda de competición

const tr = (texts) => texts[CALC_LANG];
const screen = document.getElementById("screen");

// ---------- Estado guardado en este navegador ----------
//
// cursor es el punto del recorrido principal (aprender → practicar → … → ronda), para
// continuar otro día. El repaso no mueve el cursor: al volver, se sigue donde se estaba.

const state = loadState();
let view = { phase: "hub" };

function loadState() {
  const defaults = {
    players: [],
    scores: {},
    level: 1,
    learned: [],
    cursor: { phase: "learn", mode: "main", block: 0, strat: 0 },
  };
  try {
    const saved = JSON.parse(localStorage.getItem(STORAGE_KEY));
    if (saved && saved.cursor) return { ...defaults, ...saved };
  } catch (e) { /* sin almacenamiento */ }
  return defaults;
}

function save() {
  if (view.mode === "main") state.cursor = view;
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch (e) { /* ignorar */ }
}

// ---------- Ayudas para pintar ----------

function el(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props)) {
    if (v == null || v === false) continue;
    if (k === "class") node.className = v;
    else if (k.startsWith("on")) node.addEventListener(k.slice(2), v);
    else node.setAttribute(k, v === true ? "" : v);
  }
  for (const c of children.flat()) {
    if (c != null && c !== false) node.append(c.nodeType ? c : String(c));
  }
  return node;
}

const button = (text, onclick, cls = "btn") => el("button", { class: cls, type: "button", onclick }, text);
const pts = (n) => (n === 1 ? t("point") : t("points", { n }));

function show(...nodes) {
  screen.replaceChildren(...nodes.filter(Boolean));
  window.scrollTo(0, 0);
}

function go(next) {
  view = next;
  save();
  render();
}

function render() {
  ({
    hub: renderHub,
    learn: renderLearn,
    practice: renderPractice,
    "round-intro": renderRoundIntro,
    round: renderRound,
    "round-end": renderRoundEnd,
    review: renderReview,
  })[view.phase]();
}

function stepsList(lines) {
  return el("ol", { class: "steps" }, lines.map((line) => el("li", {}, line)));
}

function opLine(p, solved) {
  return el("p", { class: "op" }, showOp(p), " = ", solved ? el("span", { class: "answer" }, f(p.answer)) : el("span", { class: "q" }, "?"));
}

// Estrategia de la que habla la vista actual del recorrido principal.
function currentStrategy(v) {
  return v.stratId ? strategyById(v.stratId) : strategiesOfBlock(v.block)[v.strat];
}

// ---------- Inicio: jugadores, dificultad, progreso y marcador ----------

function whereText() {
  const c = state.cursor;
  if (c.phase === "learn") return t("where-learn", { name: tr(currentStrategy(c).name) });
  if (c.phase === "practice") return t("where-practice", { name: tr(currentStrategy(c).name) });
  if (c.free || c.round?.free) return t("where-free");
  return t("where-round", { n: c.block + 1 });
}

function renderHub() {
  const players = el("ul", { class: "player-list" }, state.players.map((name, i) =>
    el("li", {}, el("span", {}, name), el("button", {
      type: "button",
      "aria-label": t("remove", { name }),
      onclick: () => { state.players.splice(i, 1); save(); render(); },
    }, "✕"))));

  const input = el("input", { class: "input", placeholder: t("name"), maxlength: 20, autocomplete: "off" });
  const form = el("form", {
    class: "row",
    onsubmit: (e) => {
      e.preventDefault();
      const name = input.value.trim();
      if (name && !state.players.includes(name)) state.players.push(name);
      save();
      render();
      screen.querySelector("input")?.focus();
    },
  }, input, el("button", { class: "btn", type: "submit" }, t("add")));

  const levels = el("div", { class: "segmented" }, [1, 2, 3].map((n) => el("button", {
    type: "button",
    "aria-pressed": String(state.level === n),
    onclick: () => { state.level = n; save(); render(); },
  }, t(`level${n}`))));

  const blocks = el("ul", { class: "blocks" }, BLOCKS.map((b, i) => el("li", {},
    el("h3", {}, `${b.icon} ${t("block", { n: i + 1, name: tr(b.name) })}`),
    el("div", { class: "chips" }, strategiesOfBlock(i).map((s) =>
      el("span", { class: state.learned.includes(s.id) ? "chip done" : "chip" }, `${s.icon} ${tr(s.name)}`))))));

  const started = state.learned.length > 0 || state.cursor.phase !== "learn" || state.cursor.strat > 0;
  const canPlay = state.players.length > 0;

  show(
    el("div", { class: "card" }, el("h2", {}, t("players")), players, form,
      canPlay ? null : el("p", { class: "hint" }, t("need-players"))),
    el("div", { class: "card" }, el("h2", {}, t("difficulty")), levels, el("p", { class: "hint" }, t("level-help"))),
    el("div", { class: "card" },
      el("h2", {}, t("progress")),
      el("p", { class: "label" }, t("learned-count", { n: state.learned.length, total: STRATEGIES.length })),
      blocks),
    el("div", { class: "stack" },
      el("button", {
        class: "btn big", type: "button", disabled: !canPlay,
        onclick: () => go(state.cursor),
      }, started ? `${t("continue")} · ${whereText()}` : t("start")),
      state.learned.length ? button(t("review"), () => go({ phase: "review", mode: "review", selected: [...state.learned] }), "btn big ghost") : null),
    scoreCard(state.scores, t("scoreboard"), true),
    el("div", { class: "stack" }, button(t("reset"), () => {
      if (!confirm(t("confirm-reset"))) return;
      const players = state.players;
      Object.assign(state, loadStateDefaults(), { players, level: state.level });
      save();
      render();
    }, "link-btn")),
  );
}

function loadStateDefaults() {
  return { scores: {}, learned: [], cursor: { phase: "learn", mode: "main", block: 0, strat: 0 } };
}

function scoreCard(scores, title, withReset) {
  const ranked = [...state.players].sort((a, b) => (scores[b] || 0) - (scores[a] || 0));
  const best = Math.max(0, ...ranked.map((n) => scores[n] || 0));
  return el("div", { class: "card" },
    el("h2", {}, title),
    el("ol", { class: "scores" }, ranked.map((name) =>
      el("li", { class: best > 0 && (scores[name] || 0) === best ? "top" : null },
        el("span", {}, name), el("span", { class: "pts" }, pts(scores[name] || 0))))),
    withReset && state.players.length ? button(t("reset-scores"), () => {
      if (!confirm(t("confirm-reset-scores"))) return;
      state.scores = {};
      save();
      render();
    }, "link-btn") : null);
}

// ---------- Aprender una estrategia ----------

function renderLearn() {
  const s = currentStrategy(view);
  const label = view.mode === "main"
    ? `${t("block", { n: s.block + 1, name: tr(BLOCKS[s.block].name) })} · ${t("strategy-n", { n: view.strat + 1, total: strategiesOfBlock(s.block).length })}`
    : t("block", { n: s.block + 1, name: tr(BLOCKS[s.block].name) });

  const next = view.mode === "main"
    ? button(t("practice-btn"), () => go({ ...view, phase: "practice", i: 0, problem: newPractice(s.id), shown: 0 }), "btn big")
    : el("div", { class: "stack" },
      button(t("practice-this"), () => go({ phase: "practice", mode: "review", ids: [s.id], i: 0, problem: newPractice(s.id), shown: 0, back: view.back }), "btn big"),
      button(t("back-review"), () => go(view.back), "btn big ghost"));

  show(
    el("div", { class: "card" },
      el("p", { class: "label" }, label),
      el("h2", { class: "strategy-title" }, el("span", {}, s.icon), tr(s.name)),
      el("p", {}, tr(s.idea)),
      el("div", { class: "example" },
        el("h3", {}, t("example")),
        opLine(s.example, true),
        stepsList(s.steps(s.example))),
      el("div", { class: "why" }, el("h3", {}, t("why")), el("p", {}, tr(s.why)))),
    next,
  );
}

// ---------- Práctica guiada (sin puntos) ----------

function newPractice(id) {
  const p = strategyById(id).gen(state.level);
  p.by = id;
  return p;
}

function renderPractice() {
  const p = view.problem;
  const s = strategyById(p.by);
  const steps = s.steps(p);
  const last = view.i + 1 >= EXERCISES;

  const nextExercise = () => {
    if (!last) {
      const ids = view.mode === "main" ? [s.id] : view.ids;
      go({ ...view, i: view.i + 1, problem: newPractice(pick(ids)), shown: 0 });
    } else if (view.mode === "main") {
      if (!state.learned.includes(s.id)) state.learned.push(s.id);
      const inBlock = strategiesOfBlock(view.block).length;
      go(view.strat + 1 < inBlock
        ? { phase: "learn", mode: "main", block: view.block, strat: view.strat + 1 }
        : { phase: "round-intro", mode: "main", block: view.block });
    } else {
      go(view.back);
    }
  };

  show(
    el("div", { class: "card op-card" },
      el("p", { class: "label" }, t("practice-label", { n: view.i + 1, total: EXERCISES })),
      el("p", { class: "hint" }, `${s.icon} ${tr(s.name)}`),
      opLine(p, view.shown === 2),
      view.shown === 1 ? el("p", { class: "hint-box" }, steps[0]) : null,
      view.shown === 2 ? el("div", { class: "solution" }, stepsList(steps)) : null),
    el("div", { class: "actions" },
      button(t("hint"), () => go({ ...view, shown: Math.max(view.shown, 1) }), "btn ghost"),
      button(t("solution"), () => go({ ...view, shown: 2 }), "btn ghost")),
    button(t("next"), nextExercise, "btn big"),
    view.mode === "review" ? button(t("back-review"), () => go(view.back), "link-btn") : null,
  );
}

// ---------- Rondas de competición ----------

// Pool de una ronda: tras un bloque, la mitad de las operaciones son de ese bloque
// y la otra mitad de todo lo aprendido; en las rondas libres y de repaso, todo por igual.
function newRound({ ids, newIds = [], free = false, review = false }) {
  const round = { pool: ids, newPool: newIds, free, review, index: 0, total: ROUND_LENGTH, seen: [], points: {}, last: null };
  round.problem = roundProblem(round);
  round.revealed = false;
  return round;
}

function roundProblem(r) {
  let p;
  for (let tries = 0; tries < 60; tries++) {
    const pool = r.newPool.length && Math.random() < 0.5 ? r.newPool : r.pool;
    const options = pool.length > 1 ? pool.filter((id) => id !== r.lastBy) : pool;
    const id = pick(options);
    p = strategyById(id).gen(state.level);
    p.by = id;
    if (!r.seen.includes(showOp(p))) break;
  }
  r.seen.push(showOp(p));
  r.lastBy = p.by;
  return p;
}

function mainRound(v) {
  if (v.free) return newRound({ ids: [...state.learned], free: true });
  return newRound({ ids: [...state.learned], newIds: strategiesOfBlock(v.block).map((s) => s.id) });
}

function renderRoundIntro() {
  const names = (view.ids || state.learned).map((id) => tr(strategyById(id).name));
  show(
    el("div", { class: "card" },
      el("h2", {}, view.free ? t("round-free-title") : t("round-title")),
      view.allDone ? el("p", {}, t("all-done")) : null,
      el("p", {}, t("round-rules")),
      el("p", { class: "hint" }, t("round-mix", { list: names.join(" · ") }))),
    button(t("round-start"), () => {
      const round = view.ids ? newRound({ ids: view.ids, review: true }) : mainRound(view);
      go({ ...view, phase: "round", round });
    }, "btn big"),
    view.mode === "review" ? button(t("back-review"), () => go(view.back), "link-btn") : null,
  );
}

function award(name) {
  const r = view.round;
  if (name) {
    state.scores[name] = (state.scores[name] || 0) + 1;
    r.points[name] = (r.points[name] || 0) + 1;
  }
  r.last = name;
  nextQuestion();
}

function nextQuestion() {
  const r = view.round;
  r.index++;
  if (r.index >= r.total) {
    go({ ...view, phase: "round-end" });
    return;
  }
  r.problem = roundProblem(r);
  r.revealed = false;
  go({ ...view });
}

function undoLast() {
  const r = view.round;
  if (!r.last) return;
  state.scores[r.last] = Math.max(0, (state.scores[r.last] || 0) - 1);
  r.points[r.last] = Math.max(0, (r.points[r.last] || 0) - 1);
  r.last = null;
  go({ ...view });
}

// Todas las estrategias aprendidas que sirven para la operación, empezando por la que la generó.
function quickWays(p) {
  const known = new Set([...state.learned, p.by]);
  const ways = STRATEGIES.filter((s) => known.has(s.id) && (s.id === p.by || s.fits(p)));
  ways.sort((a, b) => (a.id === p.by ? -1 : b.id === p.by ? 1 : 0));
  return ways.slice(0, 3);
}

function renderRound() {
  const r = view.round;
  const p = r.problem;

  const head = el("div", { class: "round-head" },
    el("p", { class: "label" }, t("round-label", { n: r.index + 1, total: r.total })),
    el("div", { class: "mini-scores" }, state.players.map((name) => el("span", {}, `${name} · ${r.points[name] || 0}`))));

  const card = el("div", { class: "card op-card" }, opLine(p, r.revealed));

  const controls = r.revealed
    ? el("div", {},
      el("p", { class: "who" }, t("who")),
      el("div", { class: "players-grid" },
        state.players.map((name) => button(name, () => award(name), "btn")),
        button(t("nobody"), () => award(null), "btn ghost")))
    : el("div", { class: "actions" },
      button(t("solution"), () => { r.revealed = true; go({ ...view }); }, "btn"),
      button(t("pass"), () => { r.last = null; nextQuestion(); }, "btn ghost"));

  const ways = r.revealed
    ? el("div", { class: "card solution" },
      el("h2", {}, t("quick-ways")),
      quickWays(p).map((s) => el("div", { class: "way" },
        el("h3", {}, `${s.icon} ${tr(s.name)}`),
        stepsList(s.steps(p)))))
    : null;

  show(
    head,
    card,
    controls,
    ways,
    r.last ? button(t("undo", { name: r.last }), undoLast, "link-btn") : null,
    button(t("end-round"), () => go({ ...view, phase: "round-end" }), "link-btn"),
  );
}

function renderRoundEnd() {
  const r = view.round;
  const best = Math.max(0, ...Object.values(r.points));
  const winners = state.players.filter((n) => best > 0 && (r.points[n] || 0) === best);
  let verdict = t("no-winner");
  if (winners.length === 1) verdict = t("winner", { names: winners[0] });
  else if (winners.length > 1) verdict = t("winners", { names: winners.join(t("and")) });

  let primary;
  if (view.mode === "review") {
    primary = button(t("another-round"), () => go({ ...view, phase: "round", round: newRound({ ids: view.ids, review: true }) }), "btn big");
  } else {
    const nextBlock = (view.free ? BLOCKS.length : view.block + 1);
    if (!view.free && nextBlock < BLOCKS.length) {
      primary = button(t("next-block", { n: nextBlock + 1, name: tr(BLOCKS[nextBlock].name) }),
        () => go({ phase: "learn", mode: "main", block: nextBlock, strat: 0 }), "btn big");
    } else {
      primary = button(t("another-round"),
        () => go({ phase: "round-intro", mode: "main", free: true, allDone: !view.free, block: BLOCKS.length - 1 }), "btn big");
    }
  }

  // Al acabar el último bloque, la siguiente vez que se continúe empieza una ronda libre.
  if (view.mode === "main" && !view.free && view.block === BLOCKS.length - 1) {
    state.cursor = { phase: "round-intro", mode: "main", free: true, allDone: true, block: BLOCKS.length - 1 };
  } else if (view.mode === "main" && !view.free) {
    state.cursor = { phase: "learn", mode: "main", block: view.block + 1, strat: 0 };
  } else if (view.mode === "main") {
    state.cursor = { phase: "round-intro", mode: "main", free: true, block: BLOCKS.length - 1 };
  }
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch (e) { /* ignorar */ }

  show(
    el("div", { class: "card" }, el("h2", {}, t("round-end")), el("p", { class: "who" }, verdict)),
    scoreCard(r.points, t("round-points"), false),
    scoreCard(state.scores, t("total"), false),
    el("div", { class: "stack" },
      primary,
      view.mode === "review" ? button(t("back-review"), () => go(view.back), "btn big ghost") : null,
      button(t("home"), () => { view = { phase: "hub" }; render(); }, "btn big ghost")),
  );
}

